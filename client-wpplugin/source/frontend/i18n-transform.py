#!/usr/bin/env python3
"""
Comprehensive i18n transformation script for WPTSALL client frontend.
Replaces hardcoded Chinese strings with svelte-i18n $_('key') calls.
"""
import json
import re
import os
import sys

BASE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(BASE, 'src')
LOCALES = os.path.join(BASE, '..', 'locales')

# Load existing locale files
with open(os.path.join(LOCALES, 'en.json'), 'r') as f:
    en_locale = json.load(f)
with open(os.path.join(LOCALES, 'zh-CN.json'), 'r') as f:
    zh_locale = json.load(f)

# Build reverse lookup: zh value -> key
zh_reverse = {}
for k, v in zh_locale.items():
    if v not in zh_reverse:
        zh_reverse[v] = k

# New keys to add
new_keys_en = {}
new_keys_zh = {}

def add_key(key, en_val, zh_val):
    if key not in en_locale and key not in new_keys_en:
        new_keys_en[key] = en_val
        new_keys_zh[key] = zh_val

